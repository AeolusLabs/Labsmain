import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = (name) => readFile(path.join(root, name), 'utf8')
const tokens = JSON.parse(await read('design-system/tokens.json'))
const owners = ['base', 'layout', 'components', 'pages', 'home', 'responsive', 'motion']
const values = new Map()
for (const [group, entries] of Object.entries(tokens)) {
  for (const [name, value] of Object.entries(entries)) {
    if (!/^[a-z0-9-]+$/.test(name) || !['string', 'number'].includes(typeof value)) {
      throw new Error(`Invalid token: ${group}.${name}`)
    }
    values.set(`${group}.${name}`, value)
  }
}
const property = (key) => `--${key.startsWith('aliases.') ? key.slice(8) : key.replace('.', '-')}`
function resolve(key, trail = []) {
  if (!values.has(key)) throw new Error(`Unknown token reference: ${key}`)
  if (trail.includes(key)) throw new Error(`Token cycle: ${[...trail, key].join(' → ')}`)
  return String(values.get(key)).replace(/\{([a-z0-9.-]+)\}/g, (_, reference) => {
    resolve(reference, [...trail, key])
    return `var(${property(reference)})`
  })
}
const declarations = [...values.keys()].filter((key) => !key.startsWith('breakpoint.'))
  .map((key) => `  ${property(key)}: ${resolve(key)};`).join('\n')
let css = '/* GENERATED by pnpm tokens:generate. Edit tokens.json or the owning styles/*.css, never this file. */\n'
css += '@layer tokens, base, layout, components, pages, home, responsive, motion;\n'
css += `@layer tokens {\n:root {\n${declarations}\n}\n}\n`
const external = new Set(['--font-body', '--font-display', '--reveal-delay'])
const defined = new Set([...values.keys()].map(property))
for (const owner of owners) {
  let source = await read(`styles/${owner}.css`)
  if (/#[a-f\d]{3,8}\b|\brgba?\(/i.test(source)) throw new Error(`Raw colour in styles/${owner}.css; use a token`)
  if (/(?:font-size|border-radius|letter-spacing)\s*:\s*[^;{}]*\d(?:px|rem|em)\b/.test(source)) {
    throw new Error(`Raw typography or radius in styles/${owner}.css; use a role token`)
  }
  source = source.replace(/@media \(--([a-z]+)\)/g, (_, name) => {
    const width = tokens.breakpoint[name]
    if (!Number.isFinite(width) || width <= 0) throw new Error(`Unknown breakpoint: ${name}`)
    return `@media (max-width: ${width}px)`
  })
  if (/@media[^{}]*\b\d+(px|rem|em)/.test(await read(`styles/${owner}.css`))) {
    throw new Error(`Raw breakpoint in styles/${owner}.css; use (--phone) or (--stack)`)
  }
  for (const [, name] of source.matchAll(/var\((--[a-z0-9-]+)/g)) {
    if (!defined.has(name) && !external.has(name)) throw new Error(`Undefined ${name} in styles/${owner}.css`)
  }
  css += `\n@layer ${owner} {\n${source.trim()}\n}\n`
}
const target = 'styles/system.css'
if (process.argv.includes('--check')) {
  if (await read(target) !== css) throw new Error('Generated styles are stale. Run pnpm tokens:generate.')
  console.log(`Design system OK: ${values.size} tokens; ${owners.length} ordered style owners; generated CSS current.`)
} else {
  await writeFile(path.join(root, target), css)
  console.log(`Generated ${target}`)
}
